// Explicit source import, never invoked by the application or normal UI build.
// The archive must already be downloaded at its pinned revision. Only reviewed
// processors in effect-expansion.json are copied; no SDK, binaries or UI code.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const manifest = JSON.parse(fs.readFileSync('scripts/effect-expansion.json', 'utf8'));
const source = path.resolve(`releases/research/airwin2rack-${manifest.revision}`);
const target = 'native/vendor/airwindows';
const registry = fs.readFileSync(path.join(source, 'src/ModuleAdd.h'), 'utf8');
const entries = Object.entries(manifest.groups).flatMap(([category, names]) =>
  names
    .split(' ')
    .filter(Boolean)
    .map((name) => ({ name, category })),
);
if (new Set(entries.map((e) => e.name)).size !== entries.length)
  throw new Error('Duplicate import');
const colours = {
  EQ: '#bcad66',
  Filter: '#e29b62',
  Dynamics: '#b9bac8',
  Drive: '#bb805e',
  Studio: '#859db8',
  'Lo-fi': '#c28e7c',
  Tape: '#b49169',
  Modulation: '#819fc6',
  Pitch: '#b29cce',
  Stereo: '#88aba9',
  Delay: '#69afb5',
  Reverb: '#ab93c0',
};
const declarations = [],
  factories = [],
  includes = [],
  cases = [];
fs.mkdirSync(`${target}/docs`, { recursive: true });
const copySource = (from, to) => {
  const bytes = fs.readFileSync(from);
  if (!fs.existsSync(to) || !bytes.equals(fs.readFileSync(to))) fs.writeFileSync(to, bytes);
};
for (const { name, category } of entries) {
  for (const suffix of ['.h', '.cpp', 'Proc.cpp']) {
    const file = name + suffix;
    copySource(path.join(source, 'src/autogen_airwin', file), `${target}/autogen_airwin/${file}`);
  }
  copySource(path.join(source, 'res/awpdoc', `${name}.txt`), `${target}/docs/${name}.txt`);
  const line = registry.split('\n').find((line) => line.includes(`registerAirwindow({"${name}",`));
  if (!line) throw new Error(`Missing upstream metadata ${name}`);
  const description = line.match(/(?:true|false), "([^"]*)"/)[1];
  const cpp = fs.readFileSync(`${target}/autogen_airwin/${name}.cpp`, 'utf8');
  const count = Number(
    fs
      .readFileSync(`${target}/autogen_airwin/${name}.h`, 'utf8')
      .match(/kNumParameters\s*=\s*(\d+)/)[1],
  );
  const defaults = [];
  const getters = [
    ...cpp
      .slice(cpp.indexOf(`float ${name}::getParameter(`))
      .split('getParameterName')[0]
      .matchAll(/case \w+:\s*return (\w+);/g),
  ].map((m) => m[1]);
  for (let i = 0; i < count; i++) {
    const value = cpp.match(
      new RegExp(`\\b${getters[i] || String.fromCharCode(65 + i)}\\s*=\\s*([0-9.eE+-]+)[fF]?\\s*;`),
    );
    if (!value) throw new Error(`Review defaults for ${name} ${i}`);
    defaults.push(Number((Number(value[1]) * 100).toFixed(6)));
  }
  const key = `fx-${name}`,
    file = `effects/${key}.json`;
  // Retain upstream defaults until audited. Subsequent curation edits the focused
  // descriptor, never the vendor DSP or parameter ordering.
  if (!fs.existsSync(file))
    fs.writeFileSync(
      file,
      JSON.stringify(
        {
          key,
          name: `AW ${name}`,
          type: 'Pedals',
          category,
          engine: 'Airwindows',
          detail: `${category} · Airwindows`,
          description,
          source: `https://github.com/baconpaul/airwin2rack/blob/${manifest.revision}/res/awpdoc/${name}.txt`,
          icon: category === 'EQ' ? '≋' : '◈',
          colour: colours[category],
          sync: false,
          presets: [{ name: 'Starting point', values: defaults }],
          defaults,
        },
        null,
        2,
      ) + '\n',
    );
  includes.push(`#include "vendor/airwindows/autogen_airwin/${name}.h"`);
  cases.push(
    // These pinned ClipOnly2 loops return lastSample before updating it: one
    // actual sample at all tested rates, despite their upstream spacing comment.
    `    if (key == "${name}") return std::make_unique<ImportedAirEffect>(new airwinconsolidated::${name}::${name}(0), airwinconsolidated::${name}::kNumParameters, rate, ${['BeziComp', 'Isolator3', 'ToTape8'].includes(name) ? 1 : 0});`,
  );
  factories.push(`        {"${name}", makeImportedAir},`);
}
fs.writeFileSync(
  'native/effects_air_expansion.cpp',
  '// GENERATED by scripts/import-airwindows.mjs from the curated manifest.\n#include "effects_air_import.h"\n' +
    includes.join('\n') +
    '\nstd::unique_ptr<Effect> makeImportedAir(const std::string &key, int rate)\n{\n' +
    cases.join('\n') +
    '\n    return {};\n}\n',
);
fs.writeFileSync(
  'native/effects_air_entries.inc',
  '// GENERATED by scripts/import-airwindows.mjs.\n' + factories.join('\n') + '\n',
);
const index = JSON.parse(fs.readFileSync('effects/index.json', 'utf8'));
fs.writeFileSync(
  'effects/index.json',
  JSON.stringify([...new Set([...index, ...entries.map((e) => `fx-${e.name}.json`)])], null, 2) +
    '\n',
);
console.log(`Imported ${entries.length} pinned processors and their MIT documentation.`);
// Generated C++ follows the same formatting contract as owned native adapters.
const compiler = fs
  .readdirSync('native/deps/compiler')
  .find((name) => name.startsWith('llvm-mingw-'));
execFileSync(path.resolve('native/deps/compiler', compiler, 'bin/clang-format.exe'), [
  '-i',
  'native/effects_air_expansion.cpp',
]);
